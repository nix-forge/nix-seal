//! Independent SHA-2 known-answer and incremental boundary vectors.
//! Expected bytes use CPython hashlib/OpenSSL, independently of RustCrypto.
//! Empty and abc also match the published NIST known answers.

use sha2::{Digest, Sha256, Sha512};

fn sha256_case(message: &[u8], expected: [u8; 32]) {
    assert_eq!(Sha256::digest(message).as_slice(), expected.as_slice());
    let mut incremental = Sha256::new();
    for chunk in message.chunks(7) {
        incremental.update(chunk);
    }
    assert_eq!(incremental.finalize().as_slice(), expected.as_slice());
}

fn sha512_case(message: &[u8], expected: [u8; 64]) {
    assert_eq!(Sha512::digest(message).as_slice(), expected.as_slice());
    let mut incremental = Sha512::new();
    for chunk in message.chunks(13) {
        incremental.update(chunk);
    }
    assert_eq!(incremental.finalize().as_slice(), expected.as_slice());
}

